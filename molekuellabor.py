    def _ensure_micromamba(self):
        mm = "/content/bin/micromamba"
        alt = "/content/bin/bin/micromamba"

        if os.path.exists(mm):
            return mm
        if os.path.exists(alt):
            os.makedirs("/content/bin", exist_ok=True)
            # falls es in /content/bin/bin liegt, nach /content/bin verschieben
            try:
                os.replace(alt, mm)
            except:
                return alt

        os.makedirs("/content/bin", exist_ok=True)

        # FIX: nach /content extrahieren => /content/bin/micromamba
        cmd = "curl -Ls https://micro.mamba.pm/api/micromamba/linux-64/latest | tar -xvj -C /content bin/micromamba"
        subprocess.check_call(cmd, shell=True)

        if not os.path.exists(mm) and os.path.exists(alt):
            # Fallback: wurde doch in /content/bin/bin geschrieben
            try:
                os.replace(alt, mm)
            except:
                mm = alt

        # chmod kann fehlschlagen, wenn Datei nicht existiert oder FS zickt -> nur wenn vorhanden
        if os.path.exists(mm):
            subprocess.check_call(["chmod", "+x", mm])

        if not os.path.exists(mm):
            raise RuntimeError("micromamba binary not found after extraction.")

        return mm

    def _ensure_xtb_prefix(self):
        mm = self._ensure_micromamba()
        prefix = "/content/xtb_prefix"
        xtb_bin = os.path.join(prefix, "bin", "xtb")
        if os.path.exists(xtb_bin):
            return prefix
        self.log("🧪 Advanced: Installiere xTB in separatem Prefix (conda-forge) ...")
        subprocess.check_call([mm, "create", "-y", "-p", prefix, "-c", "conda-forge", "xtb"], stdout=subprocess.DEVNULL)
        return prefix

    def _write_xyz(self, mol, path_xyz):
        conf = mol.GetConformer(0)
        lines = [str(mol.GetNumAtoms()), (mol.GetProp("_Name") if mol.HasProp("_Name") else "molecule")]
        for i, a in enumerate(mol.GetAtoms()):
            p = conf.GetAtomPosition(i)
            lines.append(f"{a.GetSymbol():2s}  {p.x: .8f}  {p.y: .8f}  {p.z: .8f}")
        with open(path_xyz, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")

    def _read_xyz_positions(self, path_xyz):
        with open(path_xyz, "r", encoding="utf-8") as f:
            lines = [ln.strip() for ln in f.readlines() if ln.strip()]
        n = int(lines[0])
        coords = []
        for i in range(n):
            parts = lines[2+i].split()
            coords.append((parts[0], float(parts[1]), float(parts[2]), float(parts[3])))
        return coords

    def optimize_xtb_micromamba(self, b):
        if self.mol is None or self.mol.GetNumConformers() == 0:
            return self.log("⚠️ Advanced xTB: Bitte erst Schritt 2 (3D Generierung).")

        self.log("🧪 Advanced: xTB (GFN2) Optimierung per externem xtb ...")

        mol_copy = Chem.Mol(self.mol)
        try:
            prefix = self._ensure_xtb_prefix()
        except Exception as e:
            self.log(f"❌ Advanced xTB: Installation/Setup fehlgeschlagen: {e}")
            return

        xtb_bin = os.path.join(prefix, "bin", "xtb")
        if not os.path.exists(xtb_bin):
            self.log("❌ Advanced xTB: xtb binary nicht gefunden.")
            return

        workdir = "/content/xtb_work"
        os.makedirs(workdir, exist_ok=True)
        xyz_in = os.path.join(workdir, "input.xyz")

        self._write_xyz(mol_copy, xyz_in)

        try:
            for fn in ["xtbopt.xyz", "xtb.out", "xtb.log"]:
                p = os.path.join(workdir, fn)
                if os.path.exists(p):
                    os.remove(p)

            cmd = [xtb_bin, "input.xyz", "--gfn", "2", "--opt"]
            self.log("   (läuft…)")
            res = subprocess.run(cmd, cwd=workdir, capture_output=True, text=True, timeout=600)

            with open(os.path.join(workdir, "xtb.out"), "w", encoding="utf-8") as f:
                f.write(res.stdout + "\n\n" + res.stderr)

            opt_xyz = os.path.join(workdir, "xtbopt.xyz")
            if res.returncode != 0 or not os.path.exists(opt_xyz):
                self.log("❌ Advanced xTB: Lauf fehlgeschlagen oder keine xtbopt.xyz erzeugt.")
                self.log("   (Dein aktuelles Molekül bleibt unverändert.)")
                self.log("   Debug: /content/xtb_work/xtb.out")
                return

        except subprocess.TimeoutExpired:
            self.log("❌ Advanced xTB: Timeout (zu lang). (Molekül bleibt unverändert.)")
            return
        except Exception as e:
            self.log(f"❌ Advanced xTB: Fehler beim Ausführen: {e} (Molekül bleibt unverändert.)")
            return

        try:
            coords = self._read_xyz_positions(opt_xyz)
            if len(coords) != mol_copy.GetNumAtoms():
                self.log("❌ Advanced xTB: Atomanzahl passt nicht – Übernahme abgebrochen.")
                return

            conf = mol_copy.GetConformer(0)
            for i, (sym, x, y, z) in enumerate(coords):
                conf.SetAtomPosition(i, Chem.rdGeometry.Point3D(x, y, z))

            self.mol = mol_copy
            # Snapshot für späteren Vergleich
            self.mol_xtb = Chem.Mol(self.mol)
            self.log("✅ Advanced xTB: Optimierung erfolgreich übernommen (GFN2-xTB).")
            self.sanity_check(self.mol, "after_xtb")
            self.clear_3d()
            self.show_mol_3d()

        except Exception as e:
            self.log(f"❌ Advanced xTB: Konnte Koordinaten nicht übernehmen: {e}")

    
