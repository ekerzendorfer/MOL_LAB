    # ---------- step 2 ----------

    def make_3d_robust(self, b):
        if self.mol_2d is None:
            return self.log("⚠️ Bitte erst Schritt 1 (Laden & 2D).")

        self.clear_3d()
        self.log("⚙️ 3D-Generierung: mehrere Konformationen → beste auswählen ...")

        base = Chem.Mol(self.mol_2d)
        try:
            Chem.SanitizeMol(base)
        except Exception as e:
            self.log(f"⚠️ Sanitize-Warnung vor 3D: {e} (wir versuchen trotzdem)")

        molH = Chem.AddHs(base)

        params = AllChem.ETKDGv3()
        params.randomSeed = 0xF00D
        params.numThreads = 0

        conf_ids = list(AllChem.EmbedMultipleConfs(molH, numConfs=self.NUM_CONFS, params=params))

        if not conf_ids:
            self.log("⚠️ ETKDGv3 fehlgeschlagen → Fallback: random coords ...")
            cid = AllChem.EmbedMolecule(molH, useRandomCoords=True, maxAttempts=self.EMBED_MAX_ATTEMPTS, randomSeed=0xF00D)
            if cid == -1:
                self.log("❌ FEHLER: 3D-Embedding gescheitert.")
                self.sanity_check(molH, "embed_failed")
                return
            conf_ids = [cid]

        best = {"E": None, "cid": None, "ff": None}
        for cid in conf_ids:
            E, ffname = self._quick_minimize_energy(molH, cid)
            if E is None:
                continue
            if best["E"] is None or E < best["E"]:
                best = {"E": E, "cid": cid, "ff": ffname}

        if best["cid"] is None:
            best["cid"] = conf_ids[0]
            best["ff"] = "unknown"
            best["E"] = float("nan")

        m_best = Chem.Mol(molH)
        m_best.RemoveAllConformers()
        m_best.AddConformer(molH.GetConformer(best["cid"]), assignId=True)

        self.mol = m_best
        self.log(f"✅ 3D erstellt: best-of {len(conf_ids)} | FF={best['ff']} | E≈{best['E']:.2f}")
        self.sanity_check(self.mol, "after_3d")
        self.show_mol_3d()

    # ---------- step 3 ----------

    def optimize_final(self, b):
        if self.mol is None or self.mol.GetNumConformers() == 0:
            return self.log("⚠️ Erst Schritt 2 (3D Generierung).")

        self.clear_3d()
        self.log("⚙️ Finale Energieminimierung ... (MMFF94 bevorzugt, sonst UFF)")

        molH = Chem.Mol(self.mol)
        used = None
        ok = False

        if self._has_mmff(molH):
            try:
                props = AllChem.MMFFGetMoleculeProperties(molH, mmffVariant='MMFF94')
                ff = AllChem.MMFFGetMoleculeForceField(molH, props, confId=0)
                ff.Initialize()
                ff.Minimize(maxIts=self.MINIMIZE_ITS_FINAL)
                used = "MMFF94"
                ok = True
            except Exception as e:
                self.log(f"⚠️ MMFF-Warnung: {e} → fallback UFF")

        if not ok:
            try:
                ff = AllChem.UFFGetMoleculeForceField(molH, confId=0)
                ff.Initialize()
                ff.Minimize(maxIts=self.MINIMIZE_ITS_FINAL)
                used = "UFF"
                ok = True
            except Exception as e:
                self.log(f"⚠️ UFF-Warnung: {e} (Optimierung evtl. unvollständig)")

        self.mol = molH
        # Snapshot für späteren Vergleich
        self.mol_mmff = Chem.Mol(self.mol)
        self.log(f"✅ Optimierung fertig. Forcefield={used}")
        self.sanity_check(self.mol, "after_opt")
        self.show_mol_3d()

