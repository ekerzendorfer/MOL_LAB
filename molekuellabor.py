    def _get_conf(self, mol):
        if mol is None or mol.GetNumConformers() == 0:
            return None
        return mol.GetConformer(0)

    def compare_mmff_xtb(self, b):
        """Vergleicht die zuletzt gespeicherten Geometrien (MMFF/UFF vs xTB).
        - gibt RMSD + max. Atomverschiebung ins Log
        - zeigt Overlay im 3D-Fenster (2 Modelle übereinander)
        - färbt xTB-Modell zusätzlich nach Verschiebungsgröße (bfactor)
        """
        if self.mol_mmff is None:
            return self.log("⚠️ Vergleich: Keine MMFF/UFF-Geometrie gespeichert. Bitte erst Schritt 3 (Optimieren) ausführen.")
        if self.mol_xtb is None:
            return self.log("⚠️ Vergleich: Keine xTB-Geometrie gespeichert. Bitte Advanced xTB einmal ausführen.")

        # Kopien, damit wir nichts am Original verändern
        m1 = Chem.Mol(self.mol_mmff)
        m2 = Chem.Mol(self.mol_xtb)

        # Optional: H raus für RMSD (robuster und didaktisch oft sinnvoll)
        m1h = Chem.RemoveHs(m1)
        m2h = Chem.RemoveHs(m2)

        try:
            # Align m2h auf m1h (in-place) und RMSD berechnen
            rmsd = rdMolAlign.AlignMol(m2h, m1h)
        except Exception as e:
            return self.log(f"❌ Vergleich: Align/RMSD fehlgeschlagen: {e}")

        # Atomverschiebungen (für farbliche Darstellung)
        c1 = self._get_conf(m1h)
        c2 = self._get_conf(m2h)
        if c1 is None or c2 is None or m1h.GetNumAtoms() != m2h.GetNumAtoms():
            return self.log("❌ Vergleich: Konformer/Atomanzahl passt nicht (unerwartet).")

        disp = []
        for i in range(m1h.GetNumAtoms()):
            p1 = c1.GetAtomPosition(i)
            p2 = c2.GetAtomPosition(i)
            d = ((p1.x-p2.x)**2 + (p1.y-p2.y)**2 + (p1.z-p2.z)**2) ** 0.5
            disp.append(d)

        maxd = max(disp) if disp else 0.0
        avgd = sum(disp)/len(disp) if disp else 0.0

        self.log(f"📐 Vergleich MMFF ↔ xTB (ohne H): RMSD = {rmsd:.3f} Å | ØΔ = {avgd:.3f} Å | maxΔ = {maxd:.3f} Å")
        self.log("   Tipp: Große Unterschiede sieht man oft besser, wenn man die Moleküle 'überlagert' oder nach Δ färbt.")

        # bfactor=Verschiebung für Farbcodierung
        for i, a in enumerate(m2h.GetAtoms()):
            a.SetProp("bfactor", f"{disp[i]:.6f}")

        # Anzeige: Overlay
        self.clear_3d()
        v = py3Dmol.view(width='100%', height=860)

        # 1) Referenz (MMFF) - halbtransparent
        sdf1 = self.mol_to_sdf_string(m1h if self.chk_show_h.value is False else Chem.AddHs(m1h, addCoords=True))
        v.addModel(sdf1, "sdf")
        v.setStyle({'model': 0}, {'stick': {'colorscheme': 'cyanCarbon', 'radius': max(getattr(self,'OVERLAY_STICK_RADIUS',0.18), 0.18)}})
        # 2) xTB - darüber
        sdf2 = self.mol_to_sdf_string(
            m2h if self.chk_show_h.value is False else Chem.AddHs(m2h, addCoords=True)
        )
        v.addModel(sdf2, "sdf")
        v.setStyle(
            {'model': 1},
            {'stick': {'colorscheme': 'magentaCarbon',
                       'radius': max(getattr(self,'OVERLAY_STICK_RADIUS',0.18), 0.18)}}
        )

        v.zoomTo()
        v.setBackgroundColor('white')
        self._viewer = v
        with self.out_3d:
            v.show()

