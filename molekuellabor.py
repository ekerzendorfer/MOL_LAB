    def sanity_check(self, mol, label=""):
        if mol is None:
            self.log(f"⚠️ Sanity({label}): Kein Molekül.")
            return
        try:
            frags = Chem.GetMolFrags(mol, asMols=False, sanitizeFrags=False)
            self.log(f"🔎 Sanity({label}): Atoms={mol.GetNumAtoms()} | Bonds={mol.GetNumBonds()} | Confs={mol.GetNumConformers()} | Fragments={len(frags)}")
        except Exception as e:
            self.log(f"⚠️ Sanity({label}) Fehler: {e}")

    def validate_smiles(self, smi):
        m = Chem.MolFromSmiles(smi)
        if not m:
            return None, "❌ Ungültiger SMILES (RDKit kann ihn nicht parsen)."
        try:
            Chem.SanitizeMol(m)
        except Exception as e:
            return m, f"⚠️ Sanitize-Warnung: {e}"
        frags = Chem.GetMolFrags(m, asMols=False, sanitizeFrags=False)
        if len(frags) > 1:
            return m, f"⚠️ Achtung: {len(frags)} Fragmente erkannt (kann zu 'fliegenden' Atomen führen)."
        return m, "✅ SMILES wirkt konsistent (Sanitize ok, 1 Fragment)."

    def draw_2d_svg(self, mol):
        rdDepictor.SetPreferCoordGen(True)
        rdDepictor.Compute2DCoords(mol)
        drawer = rdMolDraw2D.MolDraw2DSVG(520, 260)
        opts = drawer.drawOptions()
        opts.addStereoAnnotation = True
        opts.explicitMethyl = True
        opts.bondLineWidth = 2
        opts.fixedBondLength = 25
        opts.minFontSize = 14
        rdMolDraw2D.PrepareAndDrawMolecule(drawer, mol)
        drawer.FinishDrawing()
        return drawer.GetDrawingText()

    def mol_to_sdf_string(self, mol):
        buf = io.StringIO()
        w = Chem.SDWriter(buf)
        w.write(mol)
        w.flush()
        w.close()
        return buf.getvalue()

    def _has_mmff(self, molH):
        try:
            props = AllChem.MMFFGetMoleculeProperties(molH, mmffVariant='MMFF94')
            return props is not None
        except:
            return False

    def _quick_minimize_energy(self, molH, confId):
        if self._has_mmff(molH):
            try:
                props = AllChem.MMFFGetMoleculeProperties(molH, mmffVariant='MMFF94')
                ff = AllChem.MMFFGetMoleculeForceField(molH, props, confId=confId)
                ff.Initialize()
                ff.Minimize(maxIts=self.MINIMIZE_ITS_QUICK)
                return ff.CalcEnergy(), "MMFF94"
            except:
                pass
        try:
            ff = AllChem.UFFGetMoleculeForceField(molH, confId=confId)
            ff.Initialize()
            ff.Minimize(maxIts=self.MINIMIZE_ITS_QUICK)
            return ff.CalcEnergy(), "UFF"
        except:
            return None, "none"

