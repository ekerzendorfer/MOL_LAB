    def compute_conformers(self, b):
        if getattr(self, "mol_2d", None) is None:
            return self.log("⚠️ Erst Schritt 1 (Laden).")

        base_noh = Chem.RemoveHs(Chem.Mol(self.mol_2d))
        ok, reasons, meta = self._conformer_eligibility(base_noh)
        if not ok:
            return self.log("❌ Konformer-Modus nicht möglich: " + "; ".join(reasons))

        self.log("🧩 Konformer: Erzeuge Kandidaten (ETKDG) ...")
        t0 = time.time()

        molH = Chem.AddHs(Chem.Mol(self.mol_2d))
        params = AllChem.ETKDGv3()
        params.randomSeed = 0xC0FFEE
        params.pruneRmsThresh = 0.75  # Duplikate weg

        num_raw = 60
        conf_ids = list(AllChem.EmbedMultipleConfs(molH, numConfs=num_raw, params=params))
        if not conf_ids:
            return self.log("❌ Keine Konformere erzeugt (Embedding fehlgeschlagen).")

        use_mmff = AllChem.MMFFHasAllMoleculeParams(molH)
        self.conf_ff = "MMFF94" if use_mmff else "UFF"
        self.log(f"🧮 Scoring/Minimize ({self.conf_ff}) ...")

        scored = []
        for cid in conf_ids:
            if time.time() - t0 > 55:
                self.log("⏱️ Konformer-Abbruch (zu langsam).")
                break
            try:
                if use_mmff:
                    props = AllChem.MMFFGetMoleculeProperties(molH)
                    ff = AllChem.MMFFGetMoleculeForceField(molH, props, confId=cid)
                else:
                    ff = AllChem.UFFGetMoleculeForceField(molH, confId=cid)
                ff.Minimize(maxIts=250)
                E = float(ff.CalcEnergy())
                scored.append((E, cid))
            except:
                continue

        if not scored:
            return self.log("❌ Konformer-Scoring fehlgeschlagen.")

        scored.sort(key=lambda x: x[0])
        keep = scored[:10]
        Emin = keep[0][0]

        confs = []
        for E, cid in keep:
            m = Chem.Mol(molH)
            c = molH.GetConformer(cid)
            m.RemoveAllConformers()
            m.AddConformer(Chem.Conformer(c), assignId=True)
            confs.append({"mol": m, "E": float(E), "dE": float(E - Emin)})

        self.confs = confs
        self.log(f"✅ Konformer fertig: {len(confs)} (Emin={Emin:.2f} kcal/mol)")

        opts = []
        for i, d in enumerate(confs, start=1):
            opts.append((f"{i}: E={d['E']:.2f}  ΔE={d['dE']:.2f} kcal/mol", i-1))

        self.dd_conf_a.options = opts
        self.dd_conf_b.options = opts
        self.dd_conf_a.value = 0
        self.dd_conf_b.value = 1 if len(confs) > 1 else 0
        self.conf_view_mode.value = "single"

        self.show_conformer_view(None)

