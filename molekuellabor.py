    def analyze_surface(self, b):
        if self.mol is None or self.mol.GetNumConformers() == 0:
            return self.log("⚠️ Erst Schritt 2 (3D Generierung).")

        self.clear_3d()
        self.log("📊 Analyse: MW/LogP/TPSA + Partial-Charge Surface ...")

        self.mol.SetProp("MW",   f"{Descriptors.MolWt(self.mol):.2f}")
        self.mol.SetProp("LogP", f"{Crippen.MolLogP(self.mol):.2f}")
        self.mol.SetProp("TPSA", f"{Descriptors.TPSA(self.mol):.2f}")
        self.log(f"   MW: {self.mol.GetProp('MW')} | LogP: {self.mol.GetProp('LogP')} | TPSA: {self.mol.GetProp('TPSA')}")

        try:
            AllChem.ComputeGasteigerCharges(self.mol)
        except Exception as e:
            self.log(f"⚠️ Gasteiger-Warnung: {e} (Surface evtl. eingeschränkt)")

        charges = []
        for a in self.mol.GetAtoms():
            q = 0.0
            try:
                q = float(a.GetProp('_GasteigerCharge'))
                if q == q:
                    charges.append(q)
                else:
                    q = 0.0
            except:
                q = 0.0
            a.SetProp("partialCharge", f"{q:.6f}")

        m = max(0.2, max(abs(min(charges)), abs(max(charges))) if charges else 0.2)
        sat = float(self.sat_slider.value)
        cmin, cmax = -1.1*m*sat, 1.1*m*sat
        self.log(f"   Charges: {len(charges)} | Range: {cmin:.3f} .. {cmax:.3f} | Sat={sat:.2f}")

        v = py3Dmol.view(width='100%', height=860)
        m_view = self.mol if self.chk_show_h.value else Chem.RemoveHs(self.mol)
        sdf_text = self.mol_to_sdf_string(m_view)
        v.addModel(sdf_text, "sdf")

        v.setStyle({
            'stick':  {'colorscheme': self.CARBON_SCHEME, 'radius': self.STICK_RADIUS},
            'sphere': {'colorscheme': 'Jmol', 'scale': self.SPHERE_SCALE}
        })

        v.addSurface(
            py3Dmol.VDW,
            {'opacity': self.SURFACE_OPACITY,
             'colorscheme': {'prop': 'partialCharge', 'gradient': 'rwb', 'min': cmax, 'max': cmin}},
            {'model': 0}
        )

        v.zoomTo()
        v.setBackgroundColor('white')

        self._viewer = v
        with self.out_3d:
            v.show()

