    def _is_metal_free(self, mol):
        """Heuristik: erlaube nur typische Schul-Organik/Anorganik Nichtmetalle + Halogene.
        Damit fliegen Metalle wie Mg (Chlorophyll) sicher raus."""
        allowed = {1, 5, 6, 7, 8, 9, 14, 15, 16, 17, 34, 35, 53}  # H B C N O F Si P S Cl Se Br I
        for a in mol.GetAtoms():
            if a.GetAtomicNum() not in allowed:
                return False
        return True

    def _conformer_eligibility(self, mol_noh):
        """mol_noh: ohne H. Gibt (ok, reasons, meta)."""
        heavy = int(mol_noh.GetNumHeavyAtoms())
        rot = int(Descriptors.NumRotatableBonds(mol_noh))
        rings = int(mol_noh.GetRingInfo().NumRings())
        charge = int(Chem.GetFormalCharge(mol_noh))

        ok = True
        reasons = []
        if heavy > 30:
            ok = False; reasons.append(f"Heavy atoms {heavy} > 30")
        if rot > 7:
            ok = False; reasons.append(f"Rotatable bonds {rot} > 7")
        if rings > 2:
            ok = False; reasons.append(f"Rings {rings} > 2")
        if not self._is_metal_free(mol_noh):
            ok = False; reasons.append("Metall/unerlaubtes Element enthalten")
        if abs(charge) > 1:
            ok = False; reasons.append(f"Formal charge {charge} außerhalb [-1..+1]")

        meta = {"heavy_atoms": heavy, "rot_bonds": rot, "rings": rings, "charge": charge}
        return ok, reasons, meta

